// подготовленные фоны src/assets/rooms/*.webp (scripts/prep-rooms.py). Выверено по картинкам.
//
// Правило разметки (История 10): препятствие — весь силуэт мебели на картинке, от верха до
// нижнего края; ходьба (walk.ts) ещё отступает от него на PAD_X/PAD_Y. Так ноги Изика всегда
// на открытом полу, а мебель, стоящая ниже по картинке (ближе к зрителю), им не перекрывается.

