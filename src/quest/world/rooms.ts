import type { PuzzleId, RoomIndex } from '../../core/types';

export interface Pt {
  x: number;
  y: number;
}

export interface Rect {
  x: number;
  y: number;
  w: number;
  h: number;
}

export type Dir = 'down' | 'up' | 'left' | 'right';

/** Звук декоративного предмета (таблица «Декор»): нота, щелчок, «дзынь», нота вверх, мурр. */
export type DecorSfx = 'note' | 'click' | 'ding' | 'noteUp' | 'purr';

export type BrandKind = 'screen' | 'magnet' | 'poster';

export interface RoomObject {
  id: string;
  /** Название для кнопки/aria. */
  label: string;
  /** Предмет на картинке: тап по нему и свечение. */
  rect: Rect;
  /** Куда встаёт Изик, чтобы «подойти» (проходимая точка). */
  approach: Pt;
  /** Изик рядом, если до `approach` не дальше `radius`. */
  radius: number;
  puzzleId?: PuzzleId;
  decor?: { line: string; sfx: DecorSfx };
  brand?: BrandKind;
  /** Где рисовать бренд-оверлей (экран, магнит, постер). */
  brandRect?: Rect;
}

export interface DoorExit {
  /** Дверь на картинке: свечение, стрелка, тап. */
  rect: Rect;
  /** Проходимая точка у двери, куда идёт Изик по тапу. */
  approach: Pt;
  /** Переход начинается, когда Изик не дальше `radius` от `approach`. */
  radius: number;
  /** Куда Изик делает 2–3 шага, уходя в проём (может быть вне пола). */
  walkTo: Pt;
  dir: Dir;
}

export interface DoorEntry {
  /** Где Изик появляется в проёме входа; дальше сам идёт к `spawn`. */
  from: Pt;
  dir: Dir;
}

export interface DoorDef {
  /** Выход в следующую комнату; null — финальная комната (чердак). */
  exit: DoorExit | null;
  /** Вход из предыдущей; null — стартовая комната (спальня). */
  entry: DoorEntry | null;
}

export type RoomKey = 'bedroom' | 'kitchen' | 'library' | 'attic';

export interface RoomDef {
  key: RoomKey;
  title: string;
  /** URL фона 1600×900. */
  image: string;
  floor: Rect[];
  obstacles: Rect[];
  objects: RoomObject[];
  door: DoorDef;
  /** Где Изик стоит после входа и после перезагрузки (в спальне — у стола). */
  spawn: Pt;
}

/** Прямоугольник по двум углам — так удобнее сверять с сеткой на картинке. */
const r = (x1: number, y1: number, x2: number, y2: number): Rect => ({ x: x1, y: y1, w: x2 - x1, h: y2 - y1 });
const p = (x: number, y: number): Pt => ({ x, y });

